from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class TimingBatchStatus(str, Enum):
    pending = 'pending'
    blocked = 'blocked'
    ready = 'ready'
    released = 'released'
class TimingRecordStatus(str, Enum):
    pending = 'pending'
    converted = 'converted'
    blocked = 'blocked'
